// Copies the learning courses of utreys-survivors (read only) into live/course.js, unchanged: questions, options, keys,
// explanations, topics, room names, bosses, the quiz rules, the grading and the maze spec. The slice has no bundler, so the
// data goes in as one JSON global (window.COURSE). Rerun whenever the original's course data changes:
//   node tools/build-course.mjs [path to utreys-survivors]
import { pathToFileURL, fileURLToPath } from 'node:url';
import fs from 'node:fs';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url)), src = path.resolve(process.argv[2] || 'D:/Utreys-Survivors');
const mod = (f) => import(pathToFileURL(path.join(src, 'data', f)).href);
const { learningCourses } = await mod('learning-courses.js');
const { learningRules, learningGrading, learningMaze, learningRooms } = await mod('learning-rules.js');

const courses = Object.values(learningCourses);
const COURSE = { source: 'utreys-survivors/data/learning-*.js', order: courses.map((c) => c.id), courses: learningCourses, rules: learningRules, grading: learningGrading, maze: learningMaze, rooms: learningRooms };
const out = path.join(here, '..', 'live', 'course.js');
fs.writeFileSync(out, '// live/course.js: GENERATED by tools/build-course.mjs from ' + COURSE.source + ' — do not edit, rerun the tool.\n' +
  'window.COURSE = ' + JSON.stringify(COURSE) + ';\n');
const n = courses.map((c) => `${c.id}: ${c.questions.length} questions (${c.questions.filter((q) => q.type !== 'open').length} testable)`).join(', ');
console.log('wrote', out, '—', n);
